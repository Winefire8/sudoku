package com.sudokuassist

import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.os.Bundle
import android.widget.Toast
import androidx.appcompat.app.AppCompatActivity
import androidx.lifecycle.lifecycleScope
import com.sudokuassist.databinding.ActivityTestBinding
import com.sudokuassist.overlay.DigitOverlayView
import com.sudokuassist.solver.SolveResult
import com.sudokuassist.solver.SudokuSolver
import com.sudokuassist.util.Prefs
import com.sudokuassist.vision.SudokuRecognizer
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch

/**
 * Offline demo / acceptance test: runs the whole pipeline on a bundled screenshot and
 * draws the answers with the very same [DigitOverlayView] the floating overlay uses.
 *
 * This is the fastest way to verify the CV part on the device without another app.
 */
class TestActivity : AppCompatActivity() {

    private lateinit var binding: ActivityTestBinding
    private var bitmap: Bitmap? = null

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        binding = ActivityTestBinding.inflate(layoutInflater)
        setContentView(binding.root)

        // Sample images are generated by tools/make_sample.py (assets/samples).
        val sample = intent.getStringExtra(EXTRA_SAMPLE) ?: DEFAULT_SAMPLE
        bitmap = runCatching {
            assets.open(sample).use { BitmapFactory.decodeStream(it) }
        }.getOrNull()
        val bmp = bitmap
        if (bmp == null) {
            Toast.makeText(this, getString(R.string.error_sample_missing, sample), Toast.LENGTH_LONG)
                .show()
            finish()
            return
        }
        binding.testImage.setImageBitmap(bmp)
        binding.btnBack.setOnClickListener { finish() }
        binding.btnRunTest.setOnClickListener { runPipeline() }
        runPipeline()
    }

    private fun runPipeline() {
        val bmp = bitmap ?: return
        binding.btnRunTest.isEnabled = false
        val prefs = Prefs(this)
        val scale = prefs.answerScale
        val useMlKit = prefs.useMlKit
        lifecycleScope.launch(Dispatchers.Default) {
            val recognizer = SudokuRecognizer(useMlKit = useMlKit)
            val state: DigitOverlayView.State = try {
                val out = recognizer.recognize(bmp)
                if (out == null) {
                    DigitOverlayView.State(
                        null, null, false, scale, getString(R.string.error_no_grid), true
                    )
                } else {
                    when (val res = SudokuSolver.solve(out.grid.cells)) {
                        is SolveResult.Solved -> DigitOverlayView.State(
                            out.grid, res.solution, prefs.showGivens, scale, null, false
                        )
                        is SolveResult.Contradiction -> DigitOverlayView.State(
                            out.grid, null, prefs.showGivens, scale, res.message, true
                        )
                        SolveResult.NoSolution -> DigitOverlayView.State(
                            out.grid, null, prefs.showGivens, scale,
                            getString(R.string.error_no_solution), true
                        )
                    }
                }
            } catch (t: Throwable) {
                DigitOverlayView.State(
                    null, null, false, scale, t.message ?: getString(R.string.error_no_grid), true
                )
            } finally {
                recognizer.close()
            }
            launch(Dispatchers.Main) {
                binding.testOverlay.setState(state)
                binding.btnRunTest.isEnabled = true
            }
        }
    }

    override fun onDestroy() {
        binding.testOverlay.setState(null)
        binding.testImage.setImageDrawable(null)
        super.onDestroy()
    }

    companion object {
        const val EXTRA_SAMPLE = "sample"
        private const val DEFAULT_SAMPLE = "samples/sample1.png"
    }
}
